"""Write the report's appendix tables of stakeholders and requirements as LaTeX.

Three generated files go to projects/nas-sos-capstone/report/figures/tables/, which
sections/09_appendices.tex inputs:

    stakeholder_assessment.tex   every row of the "Stakeholder Assessment" sheet of
                                 knowledge/models/capstone_stakeholder_assessment.xlsx
    requirements_objectives.tex  each objective row of the ontology -> the stakeholder
                                 requirements that serve it -> system requirements -> HLRs
    requirements_decomposition.tex  stakeholder requirement -> system requirements -> HLRs
                                 (landscape; the Decomposition sheet of the review workbook)

The requirement tables read the .sysml files through tools/export_requirements_xlsx.py,
so they say what the model says (D-006). Do not edit the generated files: change the
model or the workbook and rerun this script, then compile the report.

Usage (from the repo root):
    .venv/Scripts/python.exe tools/export_report_tables.py
"""

from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

from openpyxl import load_workbook

sys.path.insert(0, str(Path(__file__).resolve().parent))
import export_requirements_xlsx as ex  # noqa: E402

REPO = ex.REPO
OUT = REPO / "projects" / "nas-sos-capstone" / "report" / "figures" / "tables"
ASSESSMENT = REPO / "knowledge" / "models" / "capstone_stakeholder_assessment.xlsx"

TEX_ESCAPES = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
               "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def tex(s) -> str:
    s = "" if s is None else str(s)
    s = "".join(TEX_ESCAPES.get(c, c) for c in s)
    s = s.replace("CO2", r"CO\textsubscript{2}").replace("->", r"$\rightarrow$")
    return s.replace("/", r"/\allowbreak{}")  # lets "Safety/separation" wrap in a narrow column


def header_note(source: str) -> str:
    return (f"% Generated by tools/export_report_tables.py on {dt.date.today():%Y-%m-%d} from {source}.\n"
            "% Do not edit: change the source and rerun the script.\n")


def col(width: str) -> str:
    return rf">{{\raggedright\arraybackslash}}p{{{width}}}"


# Opens each table: small type, tight columns, and a caption as wide as the text.
GROUP = r"\begingroup\footnotesize\setlength{\tabcolsep}{%s}\setlength{\LTcapwidth}{\textwidth}"


# ------------------------------------------------------------------ stakeholders

def stakeholder_table() -> str:
    ws = load_workbook(ASSESSMENT, data_only=True)["Stakeholder Assessment"]
    rows = list(ws.iter_rows(values_only=True))
    head, body = rows[0], [r for r in rows[1:] if r and r[1]]
    i = {h: k for k, h in enumerate(head)}
    body.sort(key=lambda r: (-(r[i["Decision Score"]] or 0), str(r[i["Stakeholder"]])))
    cols = [("PESTLE domain", "1.9cm", "PESTLE Domain"), ("Stakeholder", "3.3cm", "Stakeholder"),
            ("Stated interest", "3.2cm", "Stated Interest"), ("Trajectory impact", "1.6cm", "Trajectory-Decision Impact"),
            ("Importance", "1.6cm", "Standalone Importance"), ("Score", "0.8cm", "Decision Score"),
            ("Recommended treatment", "2.3cm", "Recommended Treatment")]
    spec = "@{}" + "".join(col(w) for _, w, _ in cols) + "@{}"
    hdr = " & ".join(rf"\textbf{{{c}}}" for c, _, _ in cols) + r" \\"
    out = [header_note("knowledge/models/capstone_stakeholder_assessment.xlsx, sheet \"Stakeholder Assessment\""),
           GROUP % "3pt",
           rf"\begin{{longtable}}{{{spec}}}",
           rf"\caption{{Stakeholder assessment: all {len(body)} candidate stakeholders, sorted by decision score (\texttt{{capstone\_stakeholder\_assessment.xlsx}}). Score is standalone importance (high 3, medium 2, low 1) plus trajectory-decision impact (yes 2, indirect 1, no 0); the workbook's other columns (MOPs, MOEs, rationale) are not shown.}}\label{{tab:stakeholder-assessment-excerpt}}\\",
           r"\toprule", hdr, r"\midrule", r"\endfirsthead",
           rf"\multicolumn{{{len(cols)}}}{{@{{}}l}}{{\textit{{Table \thetable{{}} continued}}}}\\", r"\toprule", hdr, r"\midrule", r"\endhead",
           r"\bottomrule", r"\endlastfoot"]
    for r in body:
        out.append(" & ".join(tex(r[i[k]]) for _, _, k in cols) + r" \\")
    out += [r"\end{longtable}", r"\endgroup", ""]
    return "\n".join(out)


# ------------------------------------------------------------------ requirements

def load_model():
    sn = ex.parse_requirements(ex.FILES["SN"], "SN")
    slr = ex.parse_requirements(ex.FILES["SLR"], "SLR")
    hlr = ex.parse_requirements(ex.FILES["HLR"], "HLR")
    by_name = {r["name"]: r for r in sn + slr + hlr}
    groups = list(ex.GROUP_NAMES)
    sn.sort(key=lambda r: (groups.index(ex.one(r, "stakeholderGroup")) if ex.one(r, "stakeholderGroup") in groups else 99, r["id"]))
    areas = list(dict.fromkeys(r["package"] for r in slr))
    slr.sort(key=lambda r: (areas.index(r["package"]), r["id"]))
    slr_par = {r["id"]: [by_name[n]["id"] for n in r["attrs"].get("parentNeeds", [])] for r in slr}
    hlr_par = {r["id"]: [by_name[n]["id"] for n in r["attrs"].get("parentRequirements", [])] for r in hlr}
    return sn, slr, hlr, slr_par, hlr_par


def tags(r) -> str:
    t = []
    s = ex.scope(r)
    if s in ex.SCOPE_TAGS:
        t.append(ex.SCOPE_TAGS[s].lower())
    if ex.one(r, "obligation") == "goal":
        t.append("goal")
    if ex.one(r, "architectureState") == "improved":
        t.append("improved")
    return (r"\textsc{[" + ", ".join(t) + r"]} ") if t else ""


def cell(r, seen: set, also: list[str] | None = None) -> str:
    """ID in bold and the text the first time a requirement appears; the ID alone after that."""
    rid = rf"\textbf{{{r['id']}}}"
    grey = ex.scope(r) == "outOfStudy"
    if r["id"] in seen:
        body = rf"{rid} \textit{{(text above)}}"
    else:
        seen.add(r["id"])
        body = f"{rid} {tags(r)}{tex(r['text'])}"
        if also:
            body += rf" \textit{{(also {', '.join(also)})}}"
    return rf"\textcolor{{gray}}{{{body}}}" if grey else body


def decomposition_table() -> str:
    sn, slr, hlr, slr_par, hlr_par = load_model()
    slr_under = {s["id"]: [r for r in slr if s["id"] in slr_par[r["id"]]] for s in sn}
    hlr_under = {r["id"]: [h for h in hlr if r["id"] in hlr_par[h["id"]]] for r in slr}
    spec = "@{}" + col("6.4cm") + col("7.2cm") + col("8.6cm") + "@{}"
    hdr = r"\textbf{Stakeholder requirement} & \textbf{System requirement (the NAS shall)} & \textbf{Sub-system requirement (HLR)} \\"
    n_in = sum(1 for r in slr if ex.scope(r) == "inStudy")
    out = [header_note("projects/nas-sos-capstone/cameo_models/requirements_*.sysml"),
           GROUP % "4pt",
           rf"\begin{{longtable}}{{{spec}}}",
           (rf"\caption{{Requirements decomposition: each stakeholder requirement, the system requirements that answer it, and the sub-system requirements (HLRs) that come from each. "
            rf"{len(sn)} stakeholder requirements, {len(slr)} system requirements ({n_in} in the study) and {len(hlr)} HLRs, from the SysML v2 model. "
            r"A requirement's text is given where it first appears; later appearances give its ID. Grey: out of study, with no HLR, the study's cut being made at the HLR tier. "
            r"\textsc{[background]}: held fixed as an input. \textsc{[improved]}: not done by today's NAS. \textsc{[goal]}: written with ``should''.}"
            r"\label{tab:requirements-decomposition}\\"),
           r"\toprule", hdr, r"\midrule", r"\endfirsthead",
           r"\multicolumn{3}{@{}l}{\textit{Table \thetable{} continued}}\\", r"\toprule", hdr, r"\midrule", r"\endhead",
           r"\bottomrule", r"\endlastfoot"]
    seen: set = set()
    group = None
    for s in sn:
        g = ex.GROUP_NAMES.get(ex.one(s, "stakeholderGroup"))
        if g != group:
            if group is not None:
                out.append(r"\midrule")
            group = g
            out.append(rf"\multicolumn{{3}}{{@{{}}l}}{{\textbf{{Stakeholder: {tex(g)}}}}}\\*")
        else:
            out.append(r"\cmidrule(l){1-3}")
        first_sn = True
        kids = slr_under[s["id"]]
        for k, r in enumerate(kids):
            if k:
                out.append(r"\cmidrule(l){2-3}")
            hs = hlr_under[r["id"]]
            for j, h in enumerate(hs or [None]):
                c1 = cell(s, seen) if first_sn else ""
                first_sn = False
                c2 = cell(r, seen, [p for p in slr_par[r["id"]] if p != s["id"]]) if j == 0 else ""
                if h:
                    c3 = cell(h, seen, [p for p in hlr_par[h["id"]] if p != r["id"]])
                elif ex.scope(r) == "inStudy":
                    c3 = r"\textbf{(no HLR)}"
                else:
                    c3 = r"\textcolor{gray}{\textit{no HLR: not carried into the study}}"
                out.append(f"{c1} & {c2} & {c3} " + r"\\")
    out += [r"\end{longtable}", r"\endgroup", ""]
    return "\n".join(out)


def objectives_table() -> str:
    sn, slr, hlr, slr_par, hlr_par = load_model()
    refs: dict[str, list] = {}
    for s in sn:
        for o in s["attrs"].get("objectiveRefs", []):
            refs.setdefault(o, []).append(s)
    spec = "@{}" + col("3.0cm") + col("1.8cm") + col("2.4cm") + col("2.6cm") + col("5.1cm") + col("6.4cm") + "@{}"
    hdr = (r"\textbf{Objective} & \textbf{Trajectory impact} & \textbf{Stakeholder req.\ in the study} & "
           r"\textbf{Background or out of study} & \textbf{System req.\ reached (in the study)} & \textbf{HLRs reached} \\")
    rows = ex.parse_objective_rows()
    out = [header_note("knowledge/models/stakeholder-objective-ontology.md and cameo_models/requirements_*.sysml"),
           GROUP % "3pt",
           rf"\begin{{longtable}}{{{spec}}}",
           (rf"\caption{{Stakeholder objectives traced to requirements: each of the {len(rows)} objective rows of the stakeholder objective ontology, the stakeholder requirements that serve it "
            r"(an airline requirement can serve another stakeholder's objective), and the system requirements and HLRs reached through those that are in the study or held as background.}"
            r"\label{tab:requirements-objectives}\\"),
           r"\toprule", hdr, r"\midrule", r"\endfirsthead",
           r"\multicolumn{6}{@{}l}{\textit{Table \thetable{} continued}}\\", r"\toprule", hdr, r"\midrule", r"\endhead",
           r"\bottomrule", r"\endlastfoot"]
    cat = None
    for c, o, imp in rows:
        if c != cat:
            if cat is not None:
                out.append(r"\midrule")
            cat = c
            out.append(rf"\multicolumn{{6}}{{@{{}}l}}{{\textbf{{{tex(c)}}}}}\\*")
        needs = refs.get(f"{c}: {o}", [])
        inside = [s for s in needs if ex.scope(s) == "inStudy"]
        outside = [s for s in needs if ex.scope(s) != "inStudy"]
        reached = [r for r in slr if ex.scope(r) == "inStudy"
                   and any(s["id"] in slr_par[r["id"]] for s in needs if ex.scope(s) != "outOfStudy")]
        hl = [h for h in hlr if any(r["id"] in hlr_par[h["id"]] for r in reached)]
        cells = [tex(o), tex(imp), ", ".join(s["id"] for s in inside),
                 ", ".join(f"{s['id']} ({ex.SCOPE_TAGS[ex.scope(s)].lower()})" for s in outside) or (r"\textit{none}" if not needs else ""),
                 ", ".join(r["id"] for r in reached), ", ".join(h["id"] for h in hl)]
        out.append(" & ".join(cells) + r" \\")
    loose = [s for s in sn if not s["attrs"].get("objectiveRefs")]
    if loose:
        out.append(r"\midrule")
        out.append(r"\multicolumn{6}{@{}l}{\textbf{Stakeholder requirements that name no objective row}}\\*")
        for s in loose:
            sc = ex.scope(s)
            label = f"{s['id']} ({ex.SCOPE_TAGS.get(sc, 'in study').lower()})"
            out.append(rf"\textit{{{tex(ex.GROUP_NAMES.get(ex.one(s, 'stakeholderGroup')))}}} & & " + (f"{label} & & & " if sc == "inStudy" else f" & {label} & & ") + r"\\")
    out += [r"\end{longtable}", r"\endgroup", ""]
    return "\n".join(out)


def grouped(objectives: list[str]) -> str:
    """'Airline: Fuel cost', 'Airline: Delay cost' -> 'Airline: fuel cost, delay cost', one clause per category."""
    by_cat: dict[str, list[str]] = {}
    for o in objectives:
        cat, _, row = o.partition(": ")
        by_cat.setdefault(cat, []).append(row[:1].lower() + row[1:] if row[:2] not in ("CO", "NO") else row)
    return "; ".join(f"{tex(c)}: {', '.join(tex(r) for r in rows)}" for c, rows in by_cat.items())


THREAD_SN = "SN-AIR-05"  # the stakeholder requirement the report's claims run through (owner, 2026-10-22)
# What today's NAS already does toward the thread requirement, with its source. Shortened
# from SN-AIR-05's rationale in requirements_stakeholders.sysml; keep the two in step.
THREAD_TODAY = (r"before departure, in the FAA's Collaborative Trajectory Options Program, the airline gives each of its "
                r"route options a relative cost, which the FAA's allocation uses \cite[p.~4]{kulkarni2019ctopSlotSubstitution}; "
                r"not in tactical conflict resolution in cruise")


def thread_table() -> str:
    """Body table: the thread stakeholder requirement, the objectives it serves, its system requirements and their HLRs."""
    sn, slr, hlr, slr_par, hlr_par = load_model()
    s = next(r for r in sn if r["id"] == THREAD_SN)
    kids = [r for r in slr if s["id"] in slr_par[r["id"]]]
    spec = "@{}" + col("4.4cm") + col("5.0cm") + col("6.5cm") + "@{}"
    objs = grouped(s["attrs"].get("objectiveRefs", []))
    out = [header_note("cameo_models/requirements_*.sysml"),
           r"\begin{table}[htbp]", r"\centering", r"\footnotesize\setlength{\tabcolsep}{4pt}",
           (rf"\caption{{The study's thread: {THREAD_SN}, the system requirements that answer it and the sub-system requirements (HLRs) under them, from the SysML v2 model. "
            r"\textsc{[improved]}: not done by today's NAS. \textsc{[goal]}: written with ``should''.}"),
           r"\label{tab:thread-decomposition}",
           rf"\begin{{tabular}}{{{spec}}}", r"\toprule",
           r"\textbf{Stakeholder requirement} & \textbf{System requirement (the NAS shall)} & \textbf{Sub-system requirement (HLR)} \\", r"\midrule"]
    seen: set = set()
    first = True
    for k, r in enumerate(kids):
        if k:
            out.append(r"\cmidrule(l){2-3}")
        hs = [h for h in hlr if r["id"] in hlr_par[h["id"]]]
        for j, h in enumerate(hs or [None]):
            c1 = (cell(s, seen) + rf"\par\smallskip\textit{{Done today, in part:}} {THREAD_TODAY}."
                  + rf"\par\smallskip\textit{{Objectives served:}} {objs}") if first else ""
            first = False
            c2 = cell(r, seen) if j == 0 else ""
            c3 = cell(h, seen) if h else r"\textbf{(no HLR)}"
            out.append(f"{c1} & {c2} & {c3} " + r"\\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(out)


def improvement_table() -> str:
    """Body table: every HLR tagged improved, traced up to its stakeholder requirements and the objectives they serve."""
    sn, slr, hlr, slr_par, hlr_par = load_model()
    by_id = {r["id"]: r for r in sn + slr + hlr}
    imp = [h for h in hlr if ex.one(h, "architectureState") == "improved"]
    spec = "@{}" + col("5.8cm") + col("1.6cm") + col("1.8cm") + col("6.4cm") + "@{}"
    out = [header_note("cameo_models/requirements_*.sysml"),
           r"\begin{table}[htbp]", r"\centering", r"\footnotesize\setlength{\tabcolsep}{4pt}",
           (rf"\caption{{The improvement: the {len(imp)} sub-system requirements (HLRs) that today's NAS does not meet, each traced to its system and stakeholder requirements and the objectives those serve. "
            r"The experiment's cases B to D are the means of meeting them.}"),
           r"\label{tab:improvement-hlrs}",
           rf"\begin{{tabular}}{{{spec}}}", r"\toprule",
           r"\textbf{HLR (improved)} & \textbf{System req.} & \textbf{Stakeholder req.} & \textbf{Objectives served} \\", r"\midrule"]
    for k, h in enumerate(imp):
        if k:
            out.append(r"\midrule")
        parents = hlr_par[h["id"]]
        needs = list(dict.fromkeys(n for p in parents for n in slr_par.get(p, [])
                                   if ex.scope(by_id[n]) != "outOfStudy"))  # the study's own trace only
        objs = list(dict.fromkeys(o for n in needs for o in by_id[n]["attrs"].get("objectiveRefs", [])))
        means = ex.one(h, "candidateMeans")
        txt = rf"\textbf{{{h['id']}}} {tex(h['text'])}" + (rf"\par\textit{{Means:}} {tex(means)}" if means else "")
        out.append(f"{txt} & {', '.join(parents)} & {', '.join(needs)} & {grouped(objs)} " + r"\\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(out)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in [("thread_decomposition.tex", thread_table),
                     ("improvement_hlrs.tex", improvement_table),
                     ("stakeholder_assessment.tex", stakeholder_table),
                     ("requirements_objectives.tex", objectives_table),
                     ("requirements_decomposition.tex", decomposition_table)]:
        (OUT / name).write_text(fn(), encoding="utf-8")
        print(f"Wrote {(OUT / name).relative_to(REPO)}")


if __name__ == "__main__":
    main()
